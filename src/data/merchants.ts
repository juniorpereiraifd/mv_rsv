/**
 * Fonte única de dados das lojas ("Comer Fora"). Regenerado por
 * `scripts/build_catalog.mjs` a partir de `Dados_Merch_Atualizado - Página1.csv`
 * (50 parceiros dine-in reais de São Paulo: 25 "Comer Fora" + 25 "Reservas (Get
 * In)"). As fotos próprias de cada loja ficam no mapa `PHOTOS` (photos.ts); aqui
 * mora só o conteúdo (nome, nota, ofertas, comodidades…), na ordem do mais perto
 * ao mais distante do ponto de referência usado pela home.
 *
 * A home deriva o carrossel (`featured`) e a grade (ordem do array) deste
 * catálogo, eliminando listas fixas de slug.
 */

/** Faixa de preço exibida no header da página (design 68:3750). */
export type PriceTier = '$' | '$$' | '$$$'

/** Uma oferta do bloco "Benefício pra você". */
export interface Offer {
  title: string
  subtitle: string
  /** Pills de disponibilidade, ex. ["Sáb", "Cadastro"]. */
  availability: string[]
  /** Texto completo do badge de expiração (com relógio), ex. "Expira amanhã". */
  expires?: string
  /** Regras do bottom sheet "Ver detalhes e regras" (design 97:6949). Seguem o
   * template do design; o token `{merchant}` é substituído pelo nome da loja na
   * renderização. */
  regras: string[]
}

/** Regras padrão do benefício (design 97:6949) – a validade específica da
 * oferta (dias/período) e o consumo mínimo vêm por argumento; o restante é o
 * texto padrão do design. */
function offerRegras(validity: string, minimum: string): string[] {
  return [
    validity,
    'Válido apenas na unidade {merchant} e exclusivo pra consumo no local',
    minimum,
    'Limitado ao uso de 1 cupom por pessoa',
    'Não é válido em datas comemorativas nacionais',
    'Não é válido pra menu executivo',
    'Taxa de serviço não inclusa no desconto',
  ]
}

/** Bloco "Ganhe também" (design 68:3833) – fundo clube + losango. */
export interface ClubOffer {
  title: string
  note: string
}

/** Momento compartilhado – card de avaliação com foto + avatar (design 68:3876). */
export interface SharedMoment {
  author: string
  initials: string
  rating: string
  timeAgo: string
  text: string
  /** Nº de fotos do momento – badge "+N" no card (design 68:3922). */
  photoCount?: number
}

export interface ReviewScores {
  food: number
  service: number
  atmosphere: number
}

/** Comodidade da seção "O que você pode aproveitar" – rótulo + ícone (asset). */
export interface Amenity {
  label: string
  icon: IconName
}

export interface Merchant {
  /** Identificador único da loja no catálogo (fake back-end). */
  id: string
  slug: string
  /** Nome exibido no card e no header da página. */
  name: string
  /** Categoria/cozinha, ex. "Japonesa". */
  category: string

  /* ---- Card da home (variantes de demo preservadas) ---- */
  ratingValue?: string
  ratingCount?: string
  ratingVariant?: RatingVariant
  period: PeriodVariant
  distance: string
  /** Badge de overlay na foto do Card (popular/premium/exclusivo/gourmet). */
  cardBadge?: BadgeVariant
  /** Pill de oferta do Card (cupom-r20, cashback, …). */
  cardTags?: TagsVariant
  /** Pill de oferta do MiniAnnouncementCard (oferta-local/cashback/indica). */
  announceTag?: TagsVariant
  /** Destaque da home – a loja entra no carrossel "Próximos a você". */
  featured?: boolean
  image: string
  logo: string

  /* ---- Página do restaurante (Figma 68:3750) ---- */
  priceTier: PriceTier
  hours: string
  /** Total de avaliações do header da página, ex. "999" ou "1,2 mil". */
  reviewTotal: string
  offers: Offer[]
  clubOffer: ClubOffer
  /** URLs de foto; string vazia = tile neutro com gradiente (skeleton). */
  gallery: string[]
  reviewScores: ReviewScores
  reviewSummary: string
  sharedMoments: SharedMoment[]
  about: string
  amenities: Amenity[]
  address: string
}

